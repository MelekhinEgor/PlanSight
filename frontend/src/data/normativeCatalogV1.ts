export function getNormativeForScenario(scenarioId: string): {
  pack: ScenarioNormativePack
  refs: NormativeReference[]
} {
  const pack = SCENARIO_NORMS[scenarioId] || {
    referenceIds: ['gk-748'],
    observationLinkRu: 'Требуется сопоставление наблюдения с условиями контракта и документацией.',
    formulationRu:
      'Применимое требование требует уточнения по контракту и проектной документации. Рекомендуется проверка уполномоченным специалистом.',
  }
  const refs = pack.referenceIds
    .map((id) => NORMATIVE_CATALOG_V1.find((r) => r.referenceId === id))
    .filter((r): r is NormativeReference => Boolean(r))
  return { pack, refs }
}
